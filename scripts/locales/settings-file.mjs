// The settings file (docs/design.md "Settings file"): its section on the settings screen, the note shown when an edit
// of the file is taken, and why a value was refused. Shape: Record<KeyName, Record<Locale, string>>; each row lists the
// locales in the order of LOCALES below
const LOCALES = [
  "en", "ja", "zh_CN", "zh_TW", "ko", "es", "es_419", "pt_BR", "pt_PT", "fr", "de", "it", "nl", "pl", "ru", "uk", "tr",
  "ar", "he", "fa", "hi", "bn", "id", "ms", "th", "vi", "fil", "sv", "no", "da", "fi", "cs", "el", "hu", "ro", "sk",
  "bg", "hr", "lt", "lv", "et", "sl", "ca",
];

function row(...texts) {
  if (texts.length !== LOCALES.length) throw new Error(`settings-file: ${texts.length} texts for ${LOCALES.length} locales`);
  return Object.fromEntries(LOCALES.map((locale, i) => [locale, texts[i]]));
}

